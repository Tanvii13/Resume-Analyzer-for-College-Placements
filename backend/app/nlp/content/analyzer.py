"""
Content Quality and Impact Analyzer orchestrator for Sprint 3 Module C.

Provides:
- ContentQualityAnalyzer: Evaluates project descriptions, experience entries, action verbs,
  quantifiable metrics, technical substance, and duplication.
- analyze_content_quality: Top-level convenience evaluation function.

Guarantees:
- Completely deterministic rule-based evaluation.
- No generative AI or external LLM dependencies.
- Zero fabricated metrics or synthetic candidate achievements.
- Accounts for college placement student projects lacking production metrics.
"""

from typing import Any, Dict, List, Optional, Set, Tuple
from app.nlp.content.action_verbs import (
    check_leading_action_verb,
    detect_weak_introductory_phrase,
    find_action_verbs_in_text,
)
from app.nlp.content.impact_metrics import detect_impact_metrics
from app.nlp.content.schemas import (
    CONTENT_ANALYZER_VERSION,
    ActionVerbMatch,
    BulletPointEvaluation,
    ContentQualityReport,
    DescriptionCompleteness,
    EntryQualityEvaluation,
    ImpactMetricMatch,
)
from app.nlp.content.similarity import (
    compute_jaccard_similarity,
    detect_generic_content,
    evaluate_description_substance,
    find_duplicate_bullets_across_entries,
)
from app.nlp.schemas import CandidateProfile, ExperienceEntry, ProjectEntry


class ContentQualityAnalyzer:
    """
    Evaluates project and work experience entries for technical depth,
    action-verb strength, quantifiable impact, and uniqueness.
    """

    def __init__(self, version: str = CONTENT_ANALYZER_VERSION):
        self.version = version

    def analyze(self, profile: CandidateProfile) -> ContentQualityReport:
        """
        Evaluate all project and experience descriptions in a CandidateProfile.

        Args:
            profile: CandidateProfile generated by the Sprint 2 NLP pipeline.

        Returns:
            ContentQualityReport containing per-entry evaluations and aggregate diagnostics.
        """
        entry_evaluations: List[EntryQualityEvaluation] = []
        cross_entry_bullets: List[Tuple[str, str, List[str]]] = []

        all_unique_verbs: Set[str] = set()
        all_unique_metrics: Set[str] = set()
        all_generic_warnings: List[str] = []

        # ---------------------------------------------------------------------
        # 1. Evaluate Projects
        # ---------------------------------------------------------------------
        for idx, proj in enumerate(profile.projects or [], start=1):
            entry_id = f"proj_{idx}"
            eval_res = self._evaluate_project_entry(proj, entry_id)
            entry_evaluations.append(eval_res)

            all_unique_verbs.update(eval_res.action_verbs_detected)
            all_unique_metrics.update(eval_res.impact_metrics_detected)

            # Collect bullets for duplicate check
            bullets = list(proj.highlights or [])
            if proj.description:
                bullets.append(proj.description)
            cross_entry_bullets.append((entry_id, proj.title or f"Project {idx}", bullets))

        # ---------------------------------------------------------------------
        # 2. Evaluate Experience
        # ---------------------------------------------------------------------
        for idx, exp in enumerate(profile.experience or [], start=1):
            entry_id = f"exp_{idx}"
            eval_res = self._evaluate_experience_entry(exp, entry_id, is_internship=exp.is_internship)
            entry_evaluations.append(eval_res)

            all_unique_verbs.update(eval_res.action_verbs_detected)
            all_unique_metrics.update(eval_res.impact_metrics_detected)

            bullets = list(exp.responsibilities or [])
            role_title = f"{exp.job_title or 'Role'} at {exp.company_name or 'Company'}"
            cross_entry_bullets.append((entry_id, role_title, bullets))

        # ---------------------------------------------------------------------
        # 3. Evaluate Internships (if separated)
        # ---------------------------------------------------------------------
        for idx, intern in enumerate(profile.internships or [], start=1):
            entry_id = f"intern_{idx}"
            eval_res = self._evaluate_experience_entry(intern, entry_id, is_internship=True)
            entry_evaluations.append(eval_res)

            all_unique_verbs.update(eval_res.action_verbs_detected)
            all_unique_metrics.update(eval_res.impact_metrics_detected)

            bullets = list(intern.responsibilities or [])
            role_title = f"Internship at {intern.company_name or 'Company'}"
            cross_entry_bullets.append((entry_id, role_title, bullets))

        # ---------------------------------------------------------------------
        # 4. Cross-Entry Duplicate and Generic Content Analysis
        # ---------------------------------------------------------------------
        duplicate_warnings = find_duplicate_bullets_across_entries(cross_entry_bullets)

        # Check for repeated boilerplate across entries
        for ev in entry_evaluations:
            for issue in ev.issues:
                if "generic" in issue.lower() and issue not in all_generic_warnings:
                    all_generic_warnings.append(f"{ev.entry_title} ({ev.entry_id}): {issue}")

        # ---------------------------------------------------------------------
        # 5. Aggregate Scoring & Synthesis
        # ---------------------------------------------------------------------
        total_entries = len(entry_evaluations)
        strengths: List[str] = []
        recommendations: List[str] = []

        if total_entries == 0:
            overall_score = 0.0
            recommendations.append(
                "Include at least 2 technical projects detailing programming languages, system architecture, and outcomes."
            )
        else:
            raw_average = sum(e.content_quality_score for e in entry_evaluations) / float(total_entries)

            # Penalize if duplicate content or severe generic warnings exist
            dup_penalty = min(15.0, len(duplicate_warnings) * 5.0)
            overall_score = round(max(0.0, min(100.0, raw_average - dup_penalty)), 2)

            # Generate Strengths
            if len(all_unique_verbs) >= 6:
                strengths.append(
                    f"Strong active voice: Identified {len(all_unique_verbs)} distinct technical action verbs across descriptions."
                )
            if len(all_unique_metrics) >= 3:
                strengths.append(
                    f"Quantified impact: Detected {len(all_unique_metrics)} measurable performance and scale metrics."
                )
            high_comp_count = sum(1 for e in entry_evaluations if e.description_completeness == DescriptionCompleteness.HIGH)
            if high_comp_count >= 2:
                strengths.append(
                    f"{high_comp_count} entries provide comprehensive technical depth with visible architecture."
                )

            # Generate Recommendations
            if len(all_unique_metrics) < 2:
                recommendations.append(
                    "Quantify project outcomes where possible (e.g. latency speedups, user counts, test coverage, dataset scale)."
                )
            weak_entries = [e for e in entry_evaluations if e.content_quality_score < 60.0]
            if weak_entries:
                titles = ", ".join(e.entry_title for e in weak_entries[:2])
                recommendations.append(
                    f"Flesh out descriptions for {titles} with technical action verbs and architectural contributions."
                )
            if duplicate_warnings:
                recommendations.append(
                    "Eliminate repeated bullet points across entries; communicate distinct contributions for each role."
                )

        metadata = {
            "total_projects_analyzed": len(profile.projects or []),
            "total_experience_analyzed": len(profile.experience or []) + len(profile.internships or []),
            "distinct_action_verbs_count": len(all_unique_verbs),
            "distinct_impact_metrics_count": len(all_unique_metrics),
            "duplicate_warnings_count": len(duplicate_warnings),
            "generic_warnings_count": len(all_generic_warnings),
            "achievements_count": len(profile.achievements or []),
        }

        return ContentQualityReport(
            overall_content_quality_score=overall_score,
            total_entries_analyzed=total_entries,
            entries=entry_evaluations,
            aggregate_action_verb_count=len(all_unique_verbs),
            aggregate_impact_metrics_count=len(all_unique_metrics),
            generic_content_warnings=all_generic_warnings,
            duplicate_content_warnings=duplicate_warnings,
            strengths=strengths,
            recommendations_summary=recommendations,
            analyzer_version=self.version,
            metadata=metadata,
        )

    # -------------------------------------------------------------------------
    # Helper: Evaluate Single Project Entry
    # -------------------------------------------------------------------------
    def _evaluate_project_entry(self, proj: ProjectEntry, entry_id: str) -> EntryQualityEvaluation:
        title = proj.title or f"Project {entry_id}"
        description = proj.description or ""
        highlights = proj.highlights or []
        technologies = proj.technologies or []

        # Analyze individual bullets
        all_bullet_texts = list(highlights)
        if description and description not in all_bullet_texts:
            all_bullet_texts.insert(0, description)

        bullet_evals: List[BulletPointEvaluation] = []
        action_verbs_found: Set[str] = set()
        metrics_found: Set[str] = set()
        issues: List[str] = []
        evidence: List[str] = []

        for b_text in all_bullet_texts:
            b_eval = self._evaluate_bullet(b_text)
            bullet_evals.append(b_eval)
            for v in b_eval.action_verbs:
                action_verbs_found.add(v.verb)
            for m in b_eval.impact_metrics:
                metrics_found.add(m.raw_match)
            if b_eval.is_passive_or_weak:
                issues.append(f"Passive phrasing '{b_eval.weak_phrase_found}' in bullet: '{b_text[:50]}...'")

        # Substance & Completeness Evaluation
        is_substantive, substance_defects = evaluate_description_substance(
            title=proj.title,
            description=proj.description,
            highlights=highlights,
            technologies=technologies,
        )
        issues.extend(substance_defects)

        # Determine Completeness Tier
        total_words = sum(len(b.split()) for b in all_bullet_texts)
        if not all_bullet_texts or total_words == 0:
            completeness = DescriptionCompleteness.INCOMPLETE
        elif total_words < 12 or not is_substantive:
            completeness = DescriptionCompleteness.LOW
        elif total_words >= 35 and len(action_verbs_found) >= 2:
            completeness = DescriptionCompleteness.HIGH
        else:
            completeness = DescriptionCompleteness.MODERATE

        # Compute Score (0-100)
        # Component Breakdown:
        # - Action Verbs & Active Voice: 30 pts
        # - Technical Substance & Depth: 35 pts
        # - Technologies Visibility: 15 pts
        # - Quantifiable Metrics (Bonus/Impact): 20 pts (accommodates student projects)
        earned_score = 0.0

        if completeness == DescriptionCompleteness.INCOMPLETE:
            earned_score = 0.0
        else:
            # 1. Action verbs (30 pts max)
            num_verbs = len(action_verbs_found)
            leading_count = sum(1 for be in bullet_evals if be.leading_action_verb is not None)
            if leading_count >= 2 or num_verbs >= 4:
                earned_score += 30.0
                evidence.append(f"Strong action-verb usage ({num_verbs} verbs detected: {', '.join(sorted(action_verbs_found)[:3])}).")
            elif leading_count >= 1 or num_verbs >= 2:
                earned_score += 22.0
                evidence.append(f"Action verbs present ({num_verbs} verbs).")
            elif num_verbs == 1:
                earned_score += 12.0
            else:
                issues.append("Project bullets lack strong technical action verbs.")

            # 2. Substance & Technical Depth (35 pts max)
            if completeness == DescriptionCompleteness.HIGH:
                earned_score += 35.0
                evidence.append(f"Substantial technical depth ({total_words} words across {len(bullet_evals)} items).")
            elif completeness == DescriptionCompleteness.MODERATE:
                earned_score += 24.0
            elif completeness == DescriptionCompleteness.LOW:
                earned_score += 10.0

            # 3. Technologies Visibility (15 pts max)
            if len(technologies) >= 3:
                earned_score += 15.0
                evidence.append(f"Clear technology stack identified: {', '.join(technologies[:4])}.")
            elif len(technologies) >= 1:
                earned_score += 10.0
            else:
                issues.append("No explicit technologies or frameworks listed for this project.")

            # 4. Quantifiable Metrics & Scale (20 pts max - with student accommodation)
            num_metrics = len(metrics_found)
            if num_metrics >= 2:
                earned_score += 20.0
                evidence.append(f"Demonstrates measurable impact ({', '.join(sorted(metrics_found)[:2])}).")
            elif num_metrics == 1:
                earned_score += 15.0
                evidence.append(f"Measurable outcome evidenced: {list(metrics_found)[0]}.")
            else:
                # Student project accommodation: If technical depth and action verbs are strong, award 10 pts
                if completeness == DescriptionCompleteness.HIGH and num_verbs >= 2:
                    earned_score += 10.0
                    evidence.append("Strong technical implementation details accommodating academic project scale.")
                else:
                    issues.append("Lacks measurable outcomes or quantified performance indicators.")

        # Penalties for passive phrases
        passive_count = sum(1 for be in bullet_evals if be.is_passive_or_weak)
        if passive_count > 0:
            penalty = min(12.0, passive_count * 4.0)
            earned_score = max(0.0, earned_score - penalty)

        final_score = round(max(0.0, min(100.0, earned_score)), 2)

        return EntryQualityEvaluation(
            entry_id=entry_id,
            entry_title=title,
            entry_type="project",
            content_quality_score=final_score,
            action_verbs_detected=sorted(action_verbs_found),
            impact_metrics_detected=sorted(metrics_found),
            technology_mentions=technologies,
            description_completeness=completeness,
            issues=issues,
            evidence=evidence,
            confidence=0.92 if completeness != DescriptionCompleteness.INCOMPLETE else 1.0,
            bullet_evaluations=bullet_evals,
        )

    # -------------------------------------------------------------------------
    # Helper: Evaluate Single Experience Entry
    # -------------------------------------------------------------------------
    def _evaluate_experience_entry(
        self,
        exp: ExperienceEntry,
        entry_id: str,
        is_internship: bool = False,
    ) -> EntryQualityEvaluation:
        role_type = "internship" if is_internship else "experience"
        title = f"{exp.job_title or 'Engineer'} at {exp.company_name or 'Company'}"
        responsibilities = exp.responsibilities or []
        technologies = exp.technologies_used or []

        bullet_evals: List[BulletPointEvaluation] = []
        action_verbs_found: Set[str] = set()
        metrics_found: Set[str] = set()
        issues: List[str] = []
        evidence: List[str] = []

        for b_text in responsibilities:
            b_eval = self._evaluate_bullet(b_text)
            bullet_evals.append(b_eval)
            for v in b_eval.action_verbs:
                action_verbs_found.add(v.verb)
            for m in b_eval.impact_metrics:
                metrics_found.add(m.raw_match)
            if b_eval.is_passive_or_weak:
                issues.append(f"Passive phrasing '{b_eval.weak_phrase_found}' in responsibility bullet.")

        total_words = sum(len(b.split()) for b in responsibilities)
        if not responsibilities or total_words == 0:
            completeness = DescriptionCompleteness.INCOMPLETE
            issues.append("Missing responsibility descriptions for this role.")
        elif total_words < 12:
            completeness = DescriptionCompleteness.LOW
            issues.append("Brief responsibility descriptions; detail your day-to-day contributions.")
        elif total_words >= 30 and len(action_verbs_found) >= 2:
            completeness = DescriptionCompleteness.HIGH
        else:
            completeness = DescriptionCompleteness.MODERATE

        earned_score = 0.0
        if completeness == DescriptionCompleteness.INCOMPLETE:
            earned_score = 0.0
        else:
            # Action verbs (30 pts)
            num_verbs = len(action_verbs_found)
            leading_count = sum(1 for be in bullet_evals if be.leading_action_verb is not None)
            if leading_count >= 2 or num_verbs >= 3:
                earned_score += 30.0
                evidence.append(f"Clear active voice ({num_verbs} verbs: {', '.join(sorted(action_verbs_found)[:3])}).")
            elif num_verbs >= 1:
                earned_score += 18.0
            else:
                issues.append("Responsibilities lack strong technical action verbs.")

            # Substance (35 pts)
            if completeness == DescriptionCompleteness.HIGH:
                earned_score += 35.0
                evidence.append(f"Well-explained role responsibilities ({len(responsibilities)} bullet items).")
            elif completeness == DescriptionCompleteness.MODERATE:
                earned_score += 24.0
            else:
                earned_score += 10.0

            # Tech stack (15 pts)
            if len(technologies) >= 2:
                earned_score += 15.0
                evidence.append(f"Tools & technologies applied: {', '.join(technologies[:3])}.")
            elif len(technologies) >= 1:
                earned_score += 10.0

            # Metrics (20 pts)
            num_metrics = len(metrics_found)
            if num_metrics >= 2:
                earned_score += 20.0
                evidence.append(f"Quantified engineering impact: {', '.join(sorted(metrics_found)[:2])}.")
            elif num_metrics == 1:
                earned_score += 15.0
                evidence.append(f"Impact metric evidenced: {list(metrics_found)[0]}.")
            else:
                # Student internship accommodation
                if completeness == DescriptionCompleteness.HIGH and num_verbs >= 2:
                    earned_score += 10.0
                else:
                    issues.append("Consider adding quantified outcomes (e.g. latency, tickets resolved, user scale).")

        passive_count = sum(1 for be in bullet_evals if be.is_passive_or_weak)
        if passive_count > 0:
            penalty = min(12.0, passive_count * 4.0)
            earned_score = max(0.0, earned_score - penalty)

        final_score = round(max(0.0, min(100.0, earned_score)), 2)

        return EntryQualityEvaluation(
            entry_id=entry_id,
            entry_title=title,
            entry_type=role_type,
            content_quality_score=final_score,
            action_verbs_detected=sorted(action_verbs_found),
            impact_metrics_detected=sorted(metrics_found),
            technology_mentions=technologies,
            description_completeness=completeness,
            issues=issues,
            evidence=evidence,
            confidence=0.90 if completeness != DescriptionCompleteness.INCOMPLETE else 1.0,
            bullet_evaluations=bullet_evals,
        )

    # -------------------------------------------------------------------------
    # Helper: Evaluate Single Bullet Point
    # -------------------------------------------------------------------------
    def _evaluate_bullet(self, text: str) -> BulletPointEvaluation:
        words = text.split()
        leading_verb = check_leading_action_verb(text)
        all_verbs = find_action_verbs_in_text(text)
        metrics = detect_impact_metrics(text)
        weak_phrase = detect_weak_introductory_phrase(text)

        return BulletPointEvaluation(
            bullet_text=text,
            word_count=len(words),
            leading_action_verb=leading_verb,
            action_verbs=all_verbs,
            impact_metrics=metrics,
            is_passive_or_weak=weak_phrase is not None,
            weak_phrase_found=weak_phrase,
        )


def analyze_content_quality(profile: CandidateProfile) -> ContentQualityReport:
    """Convenience helper to evaluate candidate profile content quality and impact."""
    analyzer = ContentQualityAnalyzer()
    return analyzer.analyze(profile)


