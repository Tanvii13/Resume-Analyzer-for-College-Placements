"""
Resume Scoring Engine orchestrator for Sprint 3 Module A.

Coordinates the independent scoring components:
- Section completeness (academic records, contact, core sections, fresher accommodation)
- Content quality (action verbs, quantifiable metrics, technical clarity, weak phrase avoidance)
- Skill visibility (volume, domain diversity, practical substantiation, soft skills)
- Formatting and readability (structure, bullet consistency, text density, ATS extractability)

Guarantees:
- Deterministic, explainable 0-100 placement readiness score.
- Transparent score breakdown with granular evidence and deductions.
- Strict non-discrimination: candidate identity, gender, email, phone, and institution do NOT affect score.
- Zero external API dependencies, zero LLM reliance.
"""

from typing import Dict, List, Optional
from app.nlp.schemas import CandidateProfile
from app.nlp.scoring.content_scoring import ContentQualityScorer
from app.nlp.scoring.formatting_scoring import FormattingReadabilityScorer
from app.nlp.scoring.schemas import ComponentScore, ScoreDeduction, ScoreLabel, ScoringResult
from app.nlp.scoring.section_scoring import SectionCompletenessScorer
from app.nlp.scoring.skill_scoring import SkillVisibilityScorer
from app.nlp.scoring.weights import (
    COMPONENT_CONTENT_QUALITY,
    COMPONENT_FORMATTING_READABILITY,
    COMPONENT_SECTION_COMPLETENESS,
    COMPONENT_SKILL_VISIBILITY,
    SCORING_RULE_VERSION,
    ScoringWeights,
)


class ResumeScoringEngine:
    """
    Deterministic placement-readiness scoring engine.
    Evaluates a structured CandidateProfile against collegiate recruitment benchmarks.
    """

    def __init__(
        self,
        weights: Optional[ScoringWeights] = None,
        rule_version: str = SCORING_RULE_VERSION,
    ):
        self.weights = weights or ScoringWeights.default_sprint3()
        self.rule_version = rule_version

        # Initialize individual component scorers
        self.section_scorer = SectionCompletenessScorer(
            max_score=self.weights.section_completeness
        )
        self.content_scorer = ContentQualityScorer(
            max_score=self.weights.content_quality
        )
        self.skill_scorer = SkillVisibilityScorer(
            max_score=self.weights.skill_visibility
        )
        self.formatting_scorer = FormattingReadabilityScorer(
            max_score=self.weights.formatting_readability
        )

    def evaluate(self, profile: CandidateProfile) -> ScoringResult:
        """
        Evaluate a candidate profile and generate an explainable ScoringResult.

        Args:
            profile: Validated CandidateProfile generated by the NLP pipeline.

        Returns:
            ScoringResult containing overall score, score label, component breakdowns,
            strengths, itemized deductions, and execution metadata.
        """
        component_scores: Dict[str, ComponentScore] = {}
        all_deductions: List[ScoreDeduction] = []
        all_strengths: List[str] = []

        # 1. Section Completeness Evaluation
        sec_score, sec_deductions, sec_strengths = self.section_scorer.score(profile)
        component_scores[COMPONENT_SECTION_COMPLETENESS] = sec_score
        all_deductions.extend(sec_deductions)
        all_strengths.extend(sec_strengths)

        # 2. Content Quality Evaluation
        cnt_score, cnt_deductions, cnt_strengths = self.content_scorer.score(profile)
        component_scores[COMPONENT_CONTENT_QUALITY] = cnt_score
        all_deductions.extend(cnt_deductions)
        all_strengths.extend(cnt_strengths)

        # 3. Skill Visibility Evaluation
        skl_score, skl_deductions, skl_strengths = self.skill_scorer.score(profile)
        component_scores[COMPONENT_SKILL_VISIBILITY] = skl_score
        all_deductions.extend(skl_deductions)
        all_strengths.extend(skl_strengths)

        # 4. Formatting & Readability Evaluation
        fmt_score, fmt_deductions, fmt_strengths = self.formatting_scorer.score(profile)
        component_scores[COMPONENT_FORMATTING_READABILITY] = fmt_score
        all_deductions.extend(fmt_deductions)
        all_strengths.extend(fmt_strengths)

        # Calculate Overall Score (sum of components, clamped to [0.0, 100.0])
        earned_total = sum(cs.score for cs in component_scores.values())
        overall_score = round(max(0.0, min(100.0, earned_total)), 2)

        # Derive Qualitative Label
        score_label = ScoreLabel.from_score(overall_score)

        # Deduplicate strengths while preserving order
        unique_strengths: List[str] = []
        seen_strengths = set()
        for s in all_strengths:
            if s not in seen_strengths:
                seen_strengths.add(s)
                unique_strengths.append(s)

        # Execution Diagnostics & Metadata
        metadata = {
            "rule_version": self.rule_version,
            "filename": profile.filename,
            "pipeline_version": profile.pipeline_version,
            "weights_applied": {
                COMPONENT_SECTION_COMPLETENESS: self.weights.section_completeness,
                COMPONENT_CONTENT_QUALITY: self.weights.content_quality,
                COMPONENT_SKILL_VISIBILITY: self.weights.skill_visibility,
                COMPONENT_FORMATTING_READABILITY: self.weights.formatting_readability,
            },
            "job_alignment": {
                "status": "deferred_to_sprint_4",
                "reference_weight": 20.0,
                "note": "Proportionally scaled into baseline weights for Sprint 3 readiness scoring.",
            },
            "total_deductions_count": len(all_deductions),
            "total_points_deducted": round(sum(d.points_deducted for d in all_deductions), 2),
            "pipeline_confidence": profile.metadata.overall_confidence if profile.metadata else 0.0,
        }

        return ScoringResult(
            overall_score=overall_score,
            max_score=100.0,
            score_label=score_label,
            component_scores=component_scores,
            strengths=unique_strengths,
            deductions=all_deductions,
            rule_version=self.rule_version,
            scoring_metadata=metadata,
        )


def score_resume(
    profile: CandidateProfile,
    weights: Optional[ScoringWeights] = None,
) -> ScoringResult:
    """Convenience helper to score a candidate profile with default or custom weights."""
    engine = ResumeScoringEngine(weights=weights)
    return engine.evaluate(profile)


__all__ = [
    "ResumeScoringEngine",
    "score_resume",
]
