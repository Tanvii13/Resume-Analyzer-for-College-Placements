
"""Sprint 6 - Member 3
Persistence service for officer decisions and fairness audit logs.
"""

import json
from uuid import UUID

from app.database import get_connection


ALLOWED_DECISIONS = {
    "PENDING_OFFICER_REVIEW",
    "SHORTLISTED_BY_OFFICER",
    "REJECTED_BY_OFFICER",
    "REFERRED_FOR_MANUAL_EVALUATION",
}

DECISIONS_REQUIRING_RATIONALE = {
    "SHORTLISTED_BY_OFFICER",
    "REJECTED_BY_OFFICER",
    "REFERRED_FOR_MANUAL_EVALUATION",
}


def save_placement_decision(
    resume_id,
    officer_email,
    officer_decision,
    decision_rationale=None,
    automated_score=None,
):
    """Save an authorized officer's placement decision."""

    resume_id = UUID(str(resume_id))
    decision = str(officer_decision).strip().upper()

    if decision not in ALLOWED_DECISIONS:
        raise ValueError("Unsupported officer decision.")

    if decision in DECISIONS_REQUIRING_RATIONALE:
        if (
            not isinstance(decision_rationale, str)
            or len(decision_rationale.strip()) < 15
        ):
            raise ValueError(
                "A decision rationale of at least 15 characters is required."
            )

    if automated_score is not None:
        automated_score = float(automated_score)

        if not 0 <= automated_score <= 100:
            raise ValueError(
                "Automated score must be between 0 and 100."
            )

    with get_connection() as conn:
        row = conn.execute(
            """
            INSERT INTO placement_decisions (
                resume_id,
                officer_id,
                officer_decision,
                decision_rationale,
                automated_score
            )
            SELECT
                %s,
                u.id,
                %s,
                %s,
                %s
            FROM users AS u
            WHERE LOWER(u.email) = LOWER(%s)
            RETURNING
                id,
                resume_id,
                officer_id,
                officer_decision,
                decision_rationale,
                automated_score,
                decision_timestamp
            """,
            (
                resume_id,
                decision,
                decision_rationale,
                automated_score,
                officer_email,
            ),
        ).fetchone()

    if row is None:
        raise ValueError("Officer account was not found.")

    return {
        "id": str(row[0]),
        "resume_id": str(row[1]),
        "officer_id": str(row[2]),
        "officer_decision": row[3],
        "decision_rationale": row[4],
        "automated_score": row[5],
        "decision_timestamp": row[6],
    }


def save_fairness_audit(
    resume_id,
    factor_weights,
    bias_detected,
    disparity_flags=None,
    job_id=None,
):
    """Save fairness audit results generated by Member 2."""

    resume_id = UUID(str(resume_id))

    if not isinstance(factor_weights, dict):
        raise ValueError(
            "factor_weights must be a JSON object."
        )

    if not isinstance(bias_detected, bool):
        raise ValueError(
            "bias_detected must be a boolean."
        )

    if disparity_flags is None:
        disparity_flags = []

    if not isinstance(disparity_flags, list):
        raise ValueError(
            "disparity_flags must be a list."
        )

    with get_connection() as conn:
        row = conn.execute(
            """
            INSERT INTO fairness_audit_logs (
                resume_id,
                job_id,
                factor_weights_json,
                bias_detected,
                disparity_flags
            )
            VALUES (
                %s,
                %s,
                %s::jsonb,
                %s,
                %s::jsonb
            )
            RETURNING
                id,
                resume_id,
                job_id,
                factor_weights_json,
                bias_detected,
                disparity_flags,
                audited_at
            """,
            (
                resume_id,
                str(job_id) if job_id is not None else None,
                json.dumps(factor_weights),
                bias_detected,
                json.dumps(disparity_flags),
            ),
        ).fetchone()

    return {
        "id": str(row[0]),
        "resume_id": str(row[1]),
        "job_id": row[2],
        "factor_weights": row[3],
        "bias_detected": row[4],
        "disparity_flags": row[5],
        "audited_at": row[6],
    }


def get_fairness_audit_logs(
    limit=100,
    offset=0,
    bias_only=False,
):
    """Retrieve fairness audit records."""

    if not 1 <= limit <= 500:
        raise ValueError(
            "limit must be between 1 and 500."
        )

    if offset < 0:
        raise ValueError(
            "offset cannot be negative."
        )

    with get_connection() as conn:
        rows = conn.execute(
            """
            SELECT
                id,
                resume_id,
                job_id,
                factor_weights_json,
                bias_detected,
                disparity_flags,
                audited_at
            FROM fairness_audit_logs
            WHERE (%s = FALSE OR bias_detected = TRUE)
            ORDER BY audited_at DESC
            LIMIT %s OFFSET %s
            """,
            (
                bias_only,
                limit,
                offset,
            ),
        ).fetchall()

    return [
        {
            "id": str(row[0]),
            "resume_id": str(row[1]),
            "job_id": row[2],
            "factor_weights": row[3],
            "bias_detected": row[4],
            "disparity_flags": row[5],
            "audited_at": row[6],
        }
        for row in rows
    ]


def get_decision_metrics():
    """Calculate institutional human-decision metrics."""

    with get_connection() as conn:
        row = conn.execute(
            """
            SELECT
                COUNT(*),

                COUNT(*) FILTER (
                    WHERE officer_decision =
                    'SHORTLISTED_BY_OFFICER'
                ),

                COUNT(*) FILTER (
                    WHERE officer_decision =
                    'REJECTED_BY_OFFICER'
                ),

                COUNT(*) FILTER (
                    WHERE officer_decision =
                    'REFERRED_FOR_MANUAL_EVALUATION'
                ),

                COUNT(*) FILTER (
                    WHERE officer_decision IN (
                        'SHORTLISTED_BY_OFFICER',
                        'REJECTED_BY_OFFICER'
                    )
                    AND automated_score IS NOT NULL
                    AND (
                        (
                            automated_score < 50
                            AND officer_decision =
                            'SHORTLISTED_BY_OFFICER'
                        )
                        OR
                        (
                            automated_score >= 50
                            AND officer_decision =
                            'REJECTED_BY_OFFICER'
                        )
                    )
                )

            FROM placement_decisions
            """
        ).fetchone()

    total = row[0] or 0
    potential_overrides = row[4] or 0

    return {
        "total_decisions": total,
        "shortlisted": row[1] or 0,
        "rejected": row[2] or 0,
        "referred_for_manual_evaluation": row[3] or 0,
        "potential_overrides": potential_overrides,
        "potential_override_rate_percent": round(
            potential_overrides * 100 / total,
            2,
        ) if total else 0.0,
        "note": (
            "Potential override is an advisory comparison using "
            "a 50-point threshold. It is not a measure of "
            "officer correctness."
        ),
    }
