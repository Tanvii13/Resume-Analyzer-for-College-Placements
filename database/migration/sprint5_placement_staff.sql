BEGIN;

-- ============================================================
-- 1. STAFF_RESUME_ACCESS_LOG
-- Records every time an authorised staff member (placement
-- officer or career counsellor) accesses a student's resume
-- or analysis result.
--
-- Satisfies:
--   FR-12  — placement staff view of student analysis
--   DR-07  — data governance: all staff access is auditable
--   US-14 AC-1/AC-2 — access control enforcement is in the
--                      backend/role layer; this table provides
--                      the audit trail that proves it
-- ============================================================

CREATE TABLE IF NOT EXISTS staff_resume_access_log (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    -- The placement officer or career counsellor who accessed the data
    staff_user_id UUID NOT NULL
        REFERENCES users(id)
        ON DELETE CASCADE,

    -- The student whose data was accessed
    student_user_id UUID NOT NULL
        REFERENCES users(id)
        ON DELETE CASCADE,

    -- The specific resume that was viewed
    resume_id UUID NOT NULL
        REFERENCES resumes(id)
        ON DELETE CASCADE,

    -- The analysis viewed, if applicable
    -- NULL when only resume metadata (not analysis) was accessed
    analysis_id UUID
        REFERENCES resume_analyses(id)
        ON DELETE SET NULL,

    -- What was accessed — keeps the log meaningful without over-engineering
    access_type VARCHAR(30) NOT NULL DEFAULT 'view_analysis'
        CHECK (
            access_type IN (
                'view_analysis',  -- full analysis result viewed
                'view_resume',    -- resume metadata only
                'view_skills',    -- extracted skills viewed
                'view_feedback'   -- improvement feedback viewed
            )
        ),

    accessed_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Query: all accesses by a staff member (most recent first)
CREATE INDEX IF NOT EXISTS idx_staff_access_log_staff
    ON staff_resume_access_log(staff_user_id, accessed_at DESC);

-- Query: all accesses on a specific student's data (for student's own audit view)
CREATE INDEX IF NOT EXISTS idx_staff_access_log_student
    ON staff_resume_access_log(student_user_id, accessed_at DESC);


-- ============================================================
-- 2. PLACEMENT_REPORTS
-- Stores placement summary reports generated by placement
-- officers. Caches aggregated (non-personal) statistics so
-- reports can be revisited without recomputing from scratch.
--
-- Satisfies:
--   FR-13  — placement dashboard and reports
--   DR-05  — placement data standards: reports aggregate data
--             rather than expose individual personal records
--   US-15 AC-1 — useful summary information stored and reusable
--   US-15 AC-2 — report_data holds aggregated stats only,
--                not individual student personal details
--   US-15 AC-3 — is_archived supports institutional retention
--                policies without hard-deleting records
-- ============================================================

CREATE TABLE IF NOT EXISTS placement_reports (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    -- Placement officer who generated this report
    generated_by UUID NOT NULL
        REFERENCES users(id)
        ON DELETE RESTRICT,

    -- Category of report
    report_type VARCHAR(40) NOT NULL
        CHECK (
            report_type IN (
                'overall_summary',        -- cohort-wide score averages
                'skills_gap',             -- most common missing skills across cohort
                'readiness_distribution', -- distribution of placement readiness scores
                'job_match_summary'       -- how well the cohort matches available jobs
            )
        ),

    -- Human-readable title set by the placement officer
    title VARCHAR(200) NOT NULL,

    -- Optional scope filters (e.g. batch year, department).
    -- Stored as JSONB to remain flexible across different institutions
    -- without requiring schema changes per filter type.
    filter_parameters JSONB,

    -- The computed aggregated result.
    -- Contains summary statistics only — no individual student PII.
    -- NULL while report is being generated.
    report_data JSONB,

    generated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    -- Soft-delete flag: archived reports are hidden from the UI
    -- but retained for institutional compliance (US-15 AC-3)
    is_archived BOOLEAN NOT NULL DEFAULT FALSE
);

-- Query: all active reports by a placement officer (most recent first)
CREATE INDEX IF NOT EXISTS idx_placement_reports_generated_by
    ON placement_reports(generated_by, generated_at DESC)
    WHERE is_archived = FALSE;

-- Query: filter reports by type for dashboard views
CREATE INDEX IF NOT EXISTS idx_placement_reports_type
    ON placement_reports(report_type, generated_at DESC)
    WHERE is_archived = FALSE;


COMMIT;
